"""Keep the server's public release contract identical to the Windows client."""
import inspect
from pathlib import Path
from ngs import github_updates, updates


def sync(root):
    source = '''# Generated by tools.sync_update_transport; edit the client contract, then regenerate.
import json, re, urllib.error, urllib.request
from urllib.parse import urlsplit, unquote

def check_cancel(cancel):
    if cancel.is_set(): raise InterruptedError('Update check cancelled')

'''
    for name in ('REPOSITORY', 'OFFICIAL_UPDATE_URL', 'ASSET_PREFIX'):
        source += name + ' = ' + repr(getattr(github_updates, name)) + '\n'
    source += 'VERSION_PATTERN = ' + repr(updates.VERSION_PATTERN) + '\n\n'
    source += '\n\n'.join(inspect.getsource(fn) for fn in (
        updates.validate_release, github_updates.checked_url,
        github_updates.ReleaseRedirect, github_updates.GitHubReleases))
    plugin = root / 'server/plugin'
    (plugin / 'update_transport.py').write_text(source, encoding='utf8', newline='\n')
    (plugin / 'update-public-key.bin').write_bytes((root / 'assets/update-public-key.bin').read_bytes())


if __name__ == '__main__':
    sync(Path(__file__).resolve().parents[1])
